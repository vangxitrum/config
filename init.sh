#!/bin/bash
# init.sh - install tools, then link dotfiles.
#
# Usage: ./init.sh [--headless]
#   --headless  skip desktop-only parts (i3, ghostty, dunst, fonts, fcitx5,
#               flameshot, xclip) for servers and VPSes with no display.

set -e # Exit on error

HEADLESS=false
for arg in "$@"; do
  case "$arg" in
    --headless) HEADLESS=true ;;
    -h|--help)
      sed -n '2,6p' "$0" | sed 's/^# \{0,1\}//'
      exit 0
      ;;
    *)
      echo "unknown option: $arg (try --help)" >&2
      exit 1
      ;;
  esac
done

APT_PACKAGES=(
  ripgrep
  curl
  wget
  git
  make
  sudo
  zsh
  ca-certificates
  software-properties-common
  unzip
  bsdmainutils
  fontconfig
)
$HEADLESS || APT_PACKAGES+=(xclip flameshot)

sudo apt-get update && sudo apt-get install -y "${APT_PACKAGES[@]}"

# Only clone if we are not already in a config directory
if [ ! -f "./init.sh" ]; then
  mkdir -p "$HOME/work"
  cd "$HOME/work"
  git clone https://github.com/vangxitrum/config.git
  cd config
fi

chmod +x ./install.sh ./scripts/*.sh

# terninal
./scripts/zsh.sh

# Languages
./scripts/node.sh
./scripts/python.sh
./scripts/luarocks.sh
./scripts/go.sh

# Environment and Tools
./scripts/docker.sh
./scripts/tmux.sh
./scripts/nvim.sh
./scripts/s3cmd.sh
./scripts/git.sh
./scripts/tools.sh
./scripts/agents.sh

if ! $HEADLESS; then
  ./scripts/i3.sh
  ./scripts/ghostty.sh
  ./scripts/font.sh
  ./scripts/dunst.sh

  # Install Fcitx5 for Telex (Vietnamese)
  sudo apt-get install -y fcitx5 fcitx5-unikey im-config

  # Set Fcitx5 as default input method
  im-config -n fcitx5

  # Configure Fcitx5 (Shortcuts, Telex, etc.)
  # Fcitx5 env vars live in home/.profile; input method is generated by fcitx5.sh.
  ./scripts/fcitx5.sh
fi

# Symlink all configs and home dotfiles into place.
# On a headless machine the desktop configs (i3, polybar, ...) are linked too;
# they are inert without a display and keep every machine's layout identical.
./install.sh

echo "DONE"
