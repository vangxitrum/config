#!/bin/bash

set -e # Exit on error
sudo apt-get update && sudo apt-get install -y \
  ripgrep \
  curl \
  wget \
  git \
  make \
  sudo \
  zsh \
  ca-certificates \
  software-properties-common \
  unzip \
  xclip \
  flameshot \
  bsdmainutils \
  fontconfig

# Only clone if we are not already in a config directory
if [ ! -f "./init.sh" ]; then
  mkdir -p "$HOME/work"
  cd "$HOME/work"
  git clone https://github.com/vangxitrum/config.git
  cd config
fi

chmod +x ./install.sh ./scripts/*.sh

# terninal
./scripts/zsh.sh

# Languages
./scripts/node.sh
./scripts/python.sh
./scripts/luarocks.sh
./scripts/go.sh

# Environment and Tools
./scripts/docker.sh
./scripts/i3.sh
./scripts/tmux.sh
./scripts/nvim.sh
./scripts/ghostty.sh
./scripts/font.sh
./scripts/dunst.sh
./scripts/s3cmd.sh

# Install Fcitx5 for Telex (Vietnamese)
sudo apt-get install -y fcitx5 fcitx5-unikey im-config

# Set Fcitx5 as default input method
im-config -n fcitx5

# Configure Fcitx5 (Shortcuts, Telex, etc.)
# Fcitx5 env vars live in home/.profile; input method is generated by fcitx5.sh.
./scripts/fcitx5.sh

# Symlink all configs and home dotfiles into place.
./install.sh

echo "DONE"
